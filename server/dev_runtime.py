"""Strict, read-only configuration bridge for FileShare development processes.

Importing this module never starts a process, opens a socket, or changes data.
Both Python and Electron must use the same runtime.json generated by
scripts/prepare_dev_profile.py before a development runtime may start.
"""

from __future__ import annotations

import json
import os
import secrets
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping


PORTS = {
    "owner": 15300,
    "public": 15302,
    "ipfs_api": 15301,
    "ipfs_gateway": 18081,
    "ipfs_swarm": 14001,
    "tor_control": 19351,
    "tor_socks": 19350,
}


class DevelopmentConfigurationError(RuntimeError):
    """Raised when the runtime might overlap production FileShare."""


@dataclass(frozen=True)
class DevelopmentRuntime:
    root: Path
    workspace: Path
    database: Path
    ipfs_repo: Path
    tor_data: Path
    torrc: Path
    logs: Path
    temporary: Path
    ports: Mapping[str, int]

    @property
    def owner_url(self) -> str:
        return f"http://127.0.0.1:{self.ports['owner']}"

    @property
    def public_url(self) -> str:
        return f"http://127.0.0.1:{self.ports['public']}"

    @property
    def ipfs_api_url(self) -> str:
        return f"http://127.0.0.1:{self.ports['ipfs_api']}/api/v0"

    def subprocess_environment(
        self,
        inherited: Mapping[str, str] | None = None,
    ) -> dict[str, str]:
        """Build an explicit development-only process environment.

        A fresh authentication secret is generated per development session
        and never written to runtime.json or application logs.
        """
        env = dict(
            os.environ if inherited is None else inherited
        )

        env.update({
            "FILESHARE_MODE": "development",
            "FILESHARE_DEV_PROFILE": str(
                self.workspace / "runtime.json"
            ),
            "FILESHARE_DB_PATH": str(self.database),
            "FILESHARE_TEMP_DIR": str(self.temporary),
            "FILESHARE_IPFS_API": self.ipfs_api_url,
            "FILESHARE_OWNER_HOST": "127.0.0.1",
            "FILESHARE_PUBLIC_HOST": "127.0.0.1",
            "FILESHARE_OWNER_PORT": str(
                self.ports["owner"]
            ),
            "FILESHARE_PUBLIC_PORT": str(
                self.ports["public"]
            ),
            "FILESHARE_TOR_CONTROL_PORT": str(
                self.ports["tor_control"]
            ),
            "FILESHARE_ADMIN_TOKEN": secrets.token_urlsafe(32),
            "IPFS_PATH": str(self.ipfs_repo),
            "TMP": str(self.temporary),
            "TEMP": str(self.temporary),
            "TMPDIR": str(self.temporary),
        })

        # Never inherit a production tunnel address.
        env.pop("CLEARNET_URL", None)

        return env


def _expected_paths(root: Path) -> dict[str, str]:
    workspace = root / ".fileshare-dev"

    return {
        "workspace": str(workspace),
        "database": str(
            workspace / "state" / "metadata.db"
        ),
        "ipfs_repo": str(workspace / "ipfs"),
        "tor_data": str(workspace / "tor" / "data"),
        "torrc": str(workspace / "tor" / "torrc"),
        "logs": str(workspace / "logs"),
        "temporary": str(workspace / "temporary"),
    }


def load_development_runtime(
    root: str | Path,
) -> DevelopmentRuntime:
    """Validate the development profile without starting any services."""
    project = Path(root).resolve(strict=True)

    if not (
        (project / "package.json").is_file()
        and (
            project / "server" / "server_persistent.py"
        ).is_file()
    ):
        raise DevelopmentConfigurationError(
            "This is not a FileShare source checkout"
        )

    expected = _expected_paths(project)

    manifest = (
        Path(expected["workspace"]) / "runtime.json"
    )

    try:
        payload = json.loads(
            manifest.read_text(encoding="utf-8")
        )
    except (OSError, json.JSONDecodeError) as exc:
        raise DevelopmentConfigurationError(
            "Run 'python scripts/prepare_dev_profile.py prepare' first"
        ) from exc

    if (
        not isinstance(payload, dict)
        or payload.get("version") != 1
        or payload.get("profile") != "development"
    ):
        raise DevelopmentConfigurationError(
            "Invalid development profile"
        )

    if (
        payload.get("project_root") != str(project)
        or payload.get("ports") != PORTS
        or payload.get("paths") != expected
    ):
        raise DevelopmentConfigurationError(
            "Profile location, paths or ports "
            "do not match this checkout"
        )

    workspace = Path(expected["workspace"])

    for key, raw in expected.items():
        path = Path(raw)

        # Detect symlinks and unexpected redirects.
        real = path.resolve(strict=False)

        if real != path:
            raise DevelopmentConfigurationError(
                f"Development {key} is redirected "
                "outside its assigned path"
            )

        if (
            key != "workspace"
            and not real.is_relative_to(workspace)
        ):
            raise DevelopmentConfigurationError(
                f"Development {key} escapes the workspace"
            )

    for key in (
        "workspace",
        "ipfs_repo",
        "tor_data",
        "logs",
        "temporary",
    ):
        if not Path(expected[key]).is_dir():
            raise DevelopmentConfigurationError(
                f"Missing development directory: {key}"
            )

    expected_torrc = (
        f'DataDirectory "{Path(expected["tor_data"]).as_posix()}"\n'
        'CookieAuthentication 1\n'
        f'ControlPort 127.0.0.1:{PORTS["tor_control"]}\n'
        f'SocksPort 127.0.0.1:{PORTS["tor_socks"]}\n'
        'Log notice stdout\n'
    )

    try:
        if (
            Path(expected["torrc"]).read_text(
                encoding="utf-8"
            ) != expected_torrc
        ):
            raise DevelopmentConfigurationError(
                "Unexpected Tor configuration"
            )
    except OSError as exc:
        raise DevelopmentConfigurationError(
            "Development Tor configuration is missing"
        ) from exc

    return DevelopmentRuntime(
        root=project,
        workspace=workspace,
        database=Path(expected["database"]),
        ipfs_repo=Path(expected["ipfs_repo"]),
        tor_data=Path(expected["tor_data"]),
        torrc=Path(expected["torrc"]),
        logs=Path(expected["logs"]),
        temporary=Path(expected["temporary"]),
        ports=dict(PORTS),
    )


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description=(
            "Validate FileShare Python development runtime "
            "(no services started)"
        )
    )

    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
    )

    args = parser.parse_args()

    config = load_development_runtime(args.root)

    print(
        f"Development configuration: OK\n"
        f"Owner: {config.owner_url}\n"
        f"Public: {config.public_url}\n"
        f"IPFS API: {config.ipfs_api_url}"
    )

    print(
        "No processes were started. No files were changed."
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())